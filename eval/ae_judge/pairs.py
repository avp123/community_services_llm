"""
Every response pair under evaluation, in one place.

Two families:

  AXIS PAIRS (4) -- built by axis_pairs.py. Each is one new scenario answered by the
  treatment prompt (F3) and by F3 with exactly ONE property inverted; every other line
  of the prompt is byte-identical, so the difference between the two responses is
  attributable to that axis alone.
      direction  ordered recommendation   vs  unordered options
      locality   named NJ agencies+numbers vs  generic categories
      role       practical logistics       vs  purely supportive
      language   borrowable sentences      vs  named techniques

  SCENARIO PAIRS (8) -- treatment (F3, production Version A) vs control (B, vanilla)
  on the study scenarios, generated by generate_responses.py.

Build/refresh with:  python -m eval.ae_judge.pairs
"""
import json
import pathlib

_HERE = pathlib.Path(__file__).parent
_OUT = _HERE / "output"
_DATA = _HERE.parents[1] / "debugging" / "data"

SCENARIO_PAIRS = {
    "s1_newark_housing_id": "scenario_1",
    "s2_camden_snap_transport": "scenario_2",
    "s3_paterson_disability_work": "scenario_3",
    "s5_return_to_work": "scenario_5",
    "s6_rebuild_relationships": "scenario_6",
    "s7_family_goals": "scenario_7",
    "s8_unhappy_treatment": "scenario_8",
    "s9_parents_therapy": "scenario_9",
}
AXIS_KEYS = ["direction", "locality", "role", "language"]


def build():
    axis = json.loads((_OUT / "axis_pairs.json").read_text())
    resp = json.loads((_OUT / "responses.json").read_text())
    pairs = {}
    for k in AXIS_KEYS:
        pairs[f"axis_{k}"] = {
            "family": "axis", "axis": k,
            "scenario": axis[k]["scenario"],
            "A": axis[k]["A_treatment"], "B": axis[k]["B_variant"],
            "A_label": "treatment (F3)", "B_label": f"variant: {k} inverted",
        }
    for name, sid in SCENARIO_PAIRS.items():
        pairs[name] = {
            "family": "scenario", "scenario_id": sid,
            "scenario": (_DATA / f"{sid}.md").read_text().strip(),
            "A": resp[sid]["F3"], "B": resp[sid]["B"],
            "A_label": "treatment (F3 = production Version A)",
            "B_label": "control (B, vanilla)",
        }
    (_OUT / "pairs.json").write_text(json.dumps(pairs, indent=2))

    md = ["# All evaluated response pairs\n",
          "Arm A is always the treatment. For axis pairs, arm B is the treatment with one\n"
          "property inverted; for scenario pairs, arm B is the vanilla control.\n"]
    for name, p in pairs.items():
        md += [f"\n\n{'='*90}\n## {name}  ({p['family']})\n",
               f"**A** {p['A_label']}  |  **B** {p['B_label']}\n",
               f"\n**Scenario:** {p['scenario']}\n",
               f"\n### A ({len(p['A'].split())} words)\n\n{p['A']}\n",
               f"\n### B ({len(p['B'].split())} words)\n\n{p['B']}\n"]
    (_OUT / "pairs.md").write_text("\n".join(md))
    return pairs


def load():
    return json.loads((_OUT / "pairs.json").read_text())


if __name__ == "__main__":
    p = build()
    for k, v in p.items():
        print(f"  {k:<30}{v['family']:<10}A={len(v['A'].split()):>4}w  B={len(v['B'].split()):>4}w")
    print(f"\n{len(p)} pairs -> output/pairs.json, output/pairs.md")
